<?php
/**
 * Template: My Account Profile Page
 *
 * This template controls the output for the "My Account Transactions" page
 * created by the YTISM plugin.
 *
 * How to Override:
 * Copy this file to your theme or child theme in:
 *   yourtheme/ytism/templates/my-account/profile.php
 *
 * The plugin will automatically load the overridden file instead of this one.
 * (Child theme overrides have priority over parent theme.)
 *
 * Available Variables:
 * - alias_user: Instance of YTISM\Users\AliasUser representing the current user.
 * - userdata: Array of user data retrieved from the AliasUser instance.
 * - tabs: Array of My Account tabs for the current user.
 *
 * Note: Do not edit this file inside the plugin directly, as your changes will be lost on plugin updates.
 *
