?>

<div class="ytism-myaccount-container section-dashboard">
	<!-- Left Tabs -->
	<div class="ytism-myaccount-tabs-container">
		<?php if ( ! empty( $tabs ) && is_array( $tabs ) ) : ?>
			<div class="ytism-myaccount-tabs-content">
				<h2 class="ytism-myaccount-tabs-title">
					<?php
					echo esc_html(
						sprintf(
							/* translators: %s: site name */
							__( '%s Dashboard', 'ytism' ),
							get_bloginfo( 'name' )
						)
					);
					?>
				</h2>
				<div class="ytism-myaccount-tabs">
					<?php foreach ( $tabs as $tab_key => $tabdata ) : ?>
						<div class="ytism-myaccount-tab <?php echo ( isset( $tabdata['is_active'] ) && true === $tabdata['is_active'] ) ? 'active' : ''; ?>" data-tab="<?php echo esc_attr( $tab_key ); ?>">
							<?php if ( isset( $tabdata['is_active'] ) && true === (bool) $tabdata['is_active'] ) : ?>
								<?php echo esc_html( $tabdata['label'] ); ?>
							<?php else : ?>
								<a href="<?php echo esc_url( $tabdata['url'] ); ?>"><?php echo esc_html( $tabdata['label'] ); ?></a>
							<?php endif; ?>
						</div>
					<?php endforeach; ?>
				</div>
			</div>
		<?php endif; ?>
	</div>

	<!-- Right Content -->
	<div class="ytism-myaccount-content">
		<div class="ytism-myaccount-default-content">
			<div class="ytism-myaccount-profile-page">
				<div class="ytism-myaccount-profile-card">
					<h3><?php esc_html_e( 'My Profile', 'ytism' ); ?></h3>
					<p class="subtext"><?php esc_html_e( 'View your personal details and account information', 'ytism' ); ?></p>
					<?php
					$display_name = trim( ( $userdata['first_name'] ?? '' ) . ' ' . ( $userdata['last_name'] ?? '' ) );
					$user_data    = $alias_user->get_userdata();
					$phone_number = $user_data['phoneNumber'] ?? '';
					?>
					<form class="ytism-myaccount-profile-form">
						<div class="ytism-myaccount-form-group">
							<label><?php esc_html_e( 'Full Name', 'ytism' ); ?></label>
							<input type="text" value="<?php echo esc_attr( $display_name ); ?>" readonly>
						</div>
						<div class="ytism-myaccount-form-group">
							<label><?php esc_html_e( 'Email', 'ytism' ); ?></label>
							<input type="email" value="<?php echo esc_attr( $userdata['user_email'] ?? '' ); ?>" readonly>
						</div>
						<div class="ytism-myaccount-form-group">
							<label><?php esc_html_e( 'Phone', 'ytism' ); ?></label>
							<input type="text" value="<?php echo esc_attr( $phone_number ); ?>" readonly>
						</div>
					</form>
				</div>
			</div>
		</div>
	</div>
</div>
